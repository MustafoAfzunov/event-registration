#!/usr/bin/env bash
# Generates docs/TIMELINE.md from `git log --date=iso` and the "## <timestamp> · ..." entries of
# DEVLOG.md. Nothing is typed by hand: re-run after a commit to refresh it.
set -euo pipefail
cd "$(dirname "$0")/.."
out=docs/TIMELINE.md
secs() { date -d "$1" +%s; }
human() { local s=$1; printf '%dh %02dm' $((s / 3600)) $(((s % 3600) / 60)); }

{
  echo "# Timeline"
  echo
  echo "Generated by \`scripts/timeline.sh\` on $(date -Iseconds) from \`git log --date=iso\` and \`DEVLOG.md\`."
  echo "Do not edit by hand. A commit made *after* generation (e.g. the one that adds this file) is not listed."
  echo
  echo "## Commits"
  echo
  echo "| # | Date (git, ISO) | Since previous | Commit | Subject | Files changed |"
  echo "|---|---|---|---|---|---|"
  n=0; prev=""
  while IFS=$'\t' read -r hash date subject; do
    n=$((n + 1))
    files=$(git show --stat --format= "$hash" | tail -1 | grep -oE '^ *[0-9]+ files? changed' | grep -oE '[0-9]+' || echo 0)
    since="-"; [[ -n "$prev" ]] && since=$(human $(( $(secs "$date") - $(secs "$prev") )))
    echo "| $n | $date | $since | \`$hash\` | ${subject//|/\\|} | $files |"
    prev=$date
  done < <(git log --reverse --date=iso --format='%h%x09%ad%x09%s')
  first=$(git log --reverse --date=iso --format=%ad | sed -n 1p)
  last=$(git log -1 --date=iso --format=%ad)
  echo
  echo "First commit $first, last commit $last: $(human $(( $(secs "$last") - $(secs "$first") ))) wall-clock, $n commits."
  echo
  echo "## Development log entries (DEVLOG.md)"
  echo
  echo "| Logged at | Entry |"
  echo "|---|---|"
  grep -E '^## [0-9]{4}-[0-9]{2}-[0-9]{2}T' DEVLOG.md | sed -E 's/^## ([^ ]+) · (.*)$/| \1 | \2 |/'
  echo
  echo "Details for each entry (what was done, test output, surprises, gaps) are in [DEVLOG.md](../DEVLOG.md); every design decision with its timestamp is in [DECISIONS.md](../DECISIONS.md)."
} > "$out"
echo "wrote $out ($(grep -cE '^\| [0-9]+ \| ' "$out") commit rows)"
